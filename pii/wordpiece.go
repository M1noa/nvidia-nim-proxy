// wordpiece tokenizer over vocab.txt with char offsets. mirrors bert
// basic-tokenizer folding: lowercase, nfkd, strip combining marks.
// greedy longest-match per word; unknown -> [UNK]. no whitespace split
// inside words so offsets stay exact.

type WordPiece struct {
	vocab map[string]int
	unk   int
}

func LoadWordPiece(path string) (*WordPiece, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	w := &WordPiece{vocab: map[string]int{}}
	id := 0
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		w.vocab[sc.Text()] = id
		id++
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	unk, ok := w.vocab["[UNK]"]
	if !ok {
		unk = 1
	}
	w.unk = unk
	return w, nil
}

func (w *WordPiece) ID(tok string) int {
	if id, ok := w.vocab[tok]; ok {
		return id
	}
	return w.unk
}

