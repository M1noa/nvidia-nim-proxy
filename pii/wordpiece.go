func stripCombining(s string) string {
	var b strings.Builder
	for _, r := range s {
		if unicode.Is(unicode.Mn, r) {
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// fold maps each folded byte back to the raw byte offset it came from,
// mirroring rampart foldForModel (lowercase + nfkd + strip mn).
func foldWithMap(raw string) (string, []int, []int) {
	var fb strings.Builder
	var starts, ends []int
	for i := 0; i < len(raw); {
		r, size := decodeRune(raw[i:])
		low := unicode.ToLower(r)
		// nfkd: decompose via unicode tables for latin-1 + common ranges.
		for _, d := range nfkdDecomp(low) {
			if unicode.Is(unicode.Mn, d) {
				continue
			}
			var buf [4]byte
			n := encodeRune(buf[:], d)
			fb.Write(buf[:n])
			for k := 0; k < n; k++ {
				starts = append(starts, i)
				ends = append(ends, i+size)
			}
		}
		i += size
	}
	return fb.String(), starts, ends
}

func decodeRune(b string) (rune, int) {
	if len(b) == 0 {
		return 0, 0
	}
	c := b[0]
	if c < 0x80 {
		return rune(c), 1
	}
	// minimal utf8 decode
	n := 0
	var v rune
	switch {
	case c&0xE0 == 0xC0:
		n, v = 2, rune(c&0x1F)
	case c&0xF0 == 0xE0:
		n, v = 3, rune(c&0x0F)
	default:
		n, v = 4, rune(c&0x07)
	}
	if len(b) < n {
		return 0xFFFD, 1
	}
	for i := 1; i < n; i++ {
		v = v<<6 | rune(b[i]&0x3F)
	}
	return v, n
}

func encodeRune(b []byte, r rune) int {
	if r < 0x80 {
		b[0] = byte(r)
		return 1
	}
	if r < 0x800 {
		b[0] = 0xC0 | byte(r>>6)
		b[1] = 0x80 | byte(r&0x3F)
		return 2
	}
	if r < 0x10000 {
		b[0] = 0xE0 | byte(r>>12)
		b[1] = 0x80 | byte(r>>6&0x3F)
		b[2] = 0x80 | byte(r&0x3F)
		return 3
	}
	b[0] = 0xF0 | byte(r>>18)
	b[1] = 0x80 | byte(r>>12&0x3F)
	b[2] = 0x80 | byte(r>>6&0x3F)
	b[3] = 0x80 | byte(r&0x3F)
	return 4
}

